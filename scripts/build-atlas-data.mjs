// Writes site/js/atlas-data.js (const ATLAS_DATA = …) from 3D Worlds' sourced mission catalogue and landing sites
// (atlas/src/embed/site-data.ts), for the main site's Mission catalogue and Landing sites pages.
// Run from the repo root:  node scripts/build-atlas-data.mjs   (needs atlas/node_modules: node scripts/build-atlas.mjs once)
import { build } from "../atlas/node_modules/esbuild/lib/main.js";
import { writeFileSync, mkdtempSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tmp = mkdtempSync(join(tmpdir(), "goe-atlas-data-"));
const out = join(tmp, "site-data.mjs");
await build({
  entryPoints: [join(root, "atlas/src/embed/site-data.ts")],
  bundle: true, format: "esm", platform: "node", outfile: out, logLevel: "error",
  define: { "import.meta.env.BASE_URL": '"./"', "import.meta.env.DEV": "false" },
});
const { SITE_DATA } = await import(pathToFileURL(out).href);
rmSync(tmp, { recursive: true, force: true });

const header = `/* GENERATED by scripts/build-atlas-data.mjs from atlas/src (3D Worlds) — do not edit by hand.
   Mission catalogue ${SITE_DATA.version}: ${SITE_DATA.missions.length} missions, ${Object.keys(SITE_DATA.sources).length} sources, ${SITE_DATA.sites.length} landing sites. */\n`;
writeFileSync(join(root, "site/js/atlas-data.js"), header + "const ATLAS_DATA = " + JSON.stringify(SITE_DATA) + ";\n");
console.log(`Wrote site/js/atlas-data.js: ${SITE_DATA.missions.length} missions, ${Object.keys(SITE_DATA.sources).length} sources, ${SITE_DATA.sites.length} landing sites`);
